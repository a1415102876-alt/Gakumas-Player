const TIME_SUFFIX = /-(morning|noon|evening|night|other)$/u;
const TIME_LABELS = Object.freeze({
    morning: '清晨',
    noon: '白天',
    evening: '傍晚',
    night: '夜晚',
    other: '特殊版本',
});

export function beatBackgroundLabel(value) {
    const original = String(value ?? '').trim();
    if (!original) return '';
    const filename = original.split(/[\\/]/u).at(-1).split('?')[0];
    const expanded = globalThis.HatsuBeatBackgroundRouting.expandBackground(filename).toLowerCase();
    const time = expanded.match(TIME_SUFFIX)?.[1];
    const stem = expanded.replace(TIME_SUFFIX, '').replace(/^3d-(adv|lesson)-/u, 'env_3d_$1_');
    const family = stem.startsWith('env_')
        ? stem.replace(/^env_2d_(?!adv_|other_)/u, 'env_2d_adv_')
        : `env_2d_adv_${stem}`;
    const label = BEAT_BACKGROUND_LABELS[family];
    if (!label) return original;
    const details = [family.startsWith('env_3d_') ? '3D' : '', TIME_LABELS[time]].filter(Boolean);
    return details.length ? `${label}（${details.join(' · ')}）` : label;
}
